import Foundation

/// Pasteboard type identifiers Macarum knows about.
public enum PasteboardType {
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let pdf = "com.adobe.pdf"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"

    /// Written by Macarum itself when it puts an old item back, so the monitor skips it.
    public static let macarumRestored = "id.hundredengine.macarum.restored"

    /// Types that are saved. Anything else (app private formats) is dropped to keep the
    /// store small; pasting back still works because every app reads at least one of these.
    public static let kept: [String] = [
        plainText, rtf, rtfd, html, png, tiff, jpeg, heic, pdf, fileURL, url,
    ]

    public static let images: [String] = [png, tiff, jpeg, heic]

    /// Markers from nspasteboard.org and password managers: never save such copies.
    public static let sensitive: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
        macarumRestored,
    ]
}

/// Apps whose copies are never saved, on top of the user's own list.
public enum DefaultIgnoredApps {
    public static let bundleIDs: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
    ]
}
